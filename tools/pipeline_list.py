#!/usr/bin/env python3
"""The native GS's shipped pipeline list (port/gs/native/gsn_pipeline_list.h), from data folders' lists.

    tools/pipeline_list.py [--keep] LIST_OR_FOLDER...

Every pipeline the native GS makes is written down in the data folder's native_gs_pipeline_list.txt (what Granite
made it from: its shaders, render pass and state; port/gs/native/gsn_pipeline_warm.inc), unless the shipped list has
it. At the start the pipelines of both lists for the settings in use are made on threads of their own, so that no
draw waits seconds for the driver the first time an area is seen (docs/port/RENDERER.md, "Pipelines made ahead").

This merges lists into the shipped one: each argument is a list file, or a folder searched for them (a map tour's
output: tools/map_tour.py --renderer modern --extra "..." keeps one in each map's NNN/data). The shipped list's own
lines come first unless the header is made anew (no --keep: only the lists given), in the order first seen: the
title's pipelines before the maps'. Lines another build would not make the same pipeline from are skipped by the
program itself (Granite's hash checks them), so a stale line costs nothing but room; make the list again after a
shader or Granite changes. The lists hold no game data (state and hashes only).
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "port", "gs", "native", "gsn_pipeline_list.h")
NAME = "native_gs_pipeline_list.txt"


def lists_in(path):
    if os.path.isfile(path):
        return [path]
    found = []
    for folder, _dirs, files in os.walk(path):
        if NAME in files:
            found.append(os.path.join(folder, NAME))
    return sorted(found)


def read_header():
    lines = []
    if os.path.exists(HEADER):
        with open(HEADER, encoding="ascii") as f:
            for line in f:
                m = re.match(r'\s*"(.*)",\s*$', line)
                if m and m.group(1):
                    lines.append(m.group(1))
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--keep", action="store_true", help="keep the shipped list's lines, and add these to them")
    parser.add_argument("paths", nargs="+")
    args = parser.parse_args()

    shaders, passes, entries, keys = {}, {}, [], set()

    def take(line):
        f = line.split()
        if len(f) == 3 and f[0] == "S":
            shaders.setdefault(f[1], line)
        elif len(f) == 3 and f[0] == "R":
            passes.setdefault(f[1], line)
        elif (f[0] == "G" and len(f) == 13) or (f[0] == "C" and len(f) == 7):
            key = (f[1], f[2])  # (tag, hash)
            if key not in keys:
                keys.add(key)
                entries.append(f)

    if args.keep:
        for line in read_header():
            take(line)
    files = [p for path in args.paths for p in lists_in(path)]
    if not files:
        sys.exit("pipeline_list: no %s in %s" % (NAME, ", ".join(args.paths)))
    for path in files:
        with open(path, encoding="ascii") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#"):
                    take(line)

    # the shaders and passes the entries name, then the entries
    used_shaders, used_passes = [], []
    for f in entries:
        names = [f[3]] if f[0] == "C" else [f[3], f[4]]
        for s in names:
            if s not in used_shaders:
                used_shaders.append(s)
        if f[0] == "G" and f[5] not in used_passes:
            used_passes.append(f[5])
    missing = [s for s in used_shaders if s not in shaders] + [p for p in used_passes if p not in passes]
    if missing:
        sys.exit("pipeline_list: the lists name shaders or passes they do not hold: %s" % ", ".join(missing[:5]))
    out = [shaders[s] for s in used_shaders] + [passes[p] for p in used_passes] + [" ".join(f) for f in entries]
    tags = sorted({f[1] for f in entries})
    with open(HEADER, "w", newline="\n") as h:
        h.write("/* The pipelines the native GS makes ahead (gsn_pipeline_warm.inc), from tours of the maps at the settings\n"
                "   players use. Generated by tools/pipeline_list.py from the data folders' lists\n"
                "   (native_gs_pipeline_list.txt): run it again after a shader or Granite changes.\n"
                "   %d pipelines; settings (tags): %s */\n" % (len(entries), ", ".join(tags)))
        h.write("#pragma once\n\nstatic const char *const gsn_pipeline_list[] = {\n")
        for line in out:
            h.write('    "%s",\n' % line)
        h.write('    "",\n};\n')
    print("pipeline_list: %d pipelines (%d shaders, %d render passes) from %d lists -> %s" % (
        len(entries), len(used_shaders), len(used_passes), len(files), os.path.relpath(HEADER, ROOT)))
    for t in tags:
        print("  %s: %d" % (t, sum(1 for f in entries if f[1] == t)))


if __name__ == "__main__":
    main()
